#!/usr/bin/env python3
"""Generate and verify compact 1-bit PROGMEM CJK bitmap font tables for Bruce Firmware.

Scans `src/core/lang_zh_cn.h`, `src/core/settings.cpp`, and `src/core/menu_items/ConfigMenu.cpp`
for all non-ASCII Unicode codepoints, validates that `kZhCnTable[]` is strictly sorted in
ASCII lexicographic order for binary search, and emits `src/core/cjk_font_data.h` containing
12x12 (textSize 1) and 16x16 (textSize >= 2) 1-bit PROGMEM glyph bitmaps.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from typing import Iterable

from PIL import Image, ImageDraw, ImageFont

REPO_ROOT = Path(__file__).resolve().parent.parent
LANG_HEADER = REPO_ROOT / "src" / "core" / "lang_zh_cn.h"
OUT_HEADER = REPO_ROOT / "src" / "core" / "cjk_font_data.h"
EXTRA_SCAN_FILES = [
    REPO_ROOT / "src" / "core" / "settings.cpp",
    REPO_ROOT / "src" / "core" / "menu_items" / "ConfigMenu.cpp",
    REPO_ROOT / "src" / "core" / "i18n.cpp",
]

FONT_CANDIDATES = [
    "/System/Library/Fonts/STHeiti Medium.ttc",
    "/System/Library/Fonts/PingFang.ttc",
    "/System/Library/Fonts/Hiragino Sans GB.ttc",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc",
]

EXTRA_CHARS = "简体中文语言选择返回确认取消开关是否成功失败错误警告加载中请稍候"


def find_cjk_font() -> str:
    env_font = os.environ.get("BRUCE_CJK_FONT")
    if env_font and Path(env_font).is_file():
        return env_font
    for path in FONT_CANDIDATES:
        if Path(path).is_file():
            return path
    raise RuntimeError("No Chinese TrueType/TTC font found; set BRUCE_CJK_FONT")


def parse_and_validate_table(path: Path) -> list[tuple[str, str]]:
    text = path.read_text(encoding="utf-8")
    # Match entries like {"English", "中文"},
    pattern = re.compile(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}')
    entries: list[tuple[str, str]] = []
    for m in pattern.finditer(text):
        en = bytes(m.group(1), "utf-8").decode("unicode_escape")
        zh = m.group(2).replace(r"\n", "\n").replace(r"\"", '"')
        entries.append((en, zh))

    if not entries:
        raise ValueError(f"No translation entries found in {path}")

    # Verify strict ASCII byte sort order matching C `strcmp`
    for i in range(1, len(entries)):
        prev_en = entries[i - 1][0].encode("utf-8")
        curr_en = entries[i][0].encode("utf-8")
        if prev_en >= curr_en:
            raise ValueError(
                f"kZhCnTable not strictly sorted at index {i}: "
                f"{entries[i - 1][0]!r} >= {entries[i][0]!r}"
            )
    return entries


def collect_codepoints(entries: Iterable[tuple[str, str]]) -> list[int]:
    cps: set[int] = set()
    for _, zh in entries:
        for ch in zh:
            if ord(ch) >= 0x80:
                cps.add(ord(ch))
    for ch in EXTRA_CHARS:
        if ord(ch) >= 0x80:
            cps.add(ord(ch))
    for p in EXTRA_SCAN_FILES:
        if p.is_file():
            for ch in p.read_text(encoding="utf-8", errors="ignore"):
                if ord(ch) >= 0x80:
                    cps.add(ord(ch))
    return sorted(cps)


def rasterize_glyph(ch: str, font: ImageFont.FreeTypeFont, size: int) -> list[int]:
    img = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(img)
    bbox = draw.textbbox((0, 0), ch, font=font)
    w = bbox[2] - bbox[0]
    h = bbox[3] - bbox[1]
    x = (size - w) // 2 - bbox[0]
    y = (size - h) // 2 - bbox[1]
    draw.text((x, y), ch, font=font, fill=255)

    # Adaptive threshold: keep strokes crisp even at 12x12
    thresh = 96 if size <= 12 else 112
    rows: list[int] = []
    px = img.load()
    for ry in range(size):
        bits = 0
        for rx in range(size):
            if px[rx, ry] >= thresh:
                bits |= 1 << (size - 1 - rx)
        rows.append(bits)
    return rows


def generate_header(codepoints: list[int], font_path: str) -> str:
    font12 = ImageFont.truetype(font_path, 11)
    font16 = ImageFont.truetype(font_path, 14)

    lines: list[str] = [
        "// AUTOGENERATED by tools/gen_cjk_font.py - DO NOT EDIT BY HAND",
        "#ifndef __BRUCE_CJK_FONT_DATA_H__",
        "#define __BRUCE_CJK_FONT_DATA_H__",
        "",
        "#include <Arduino.h>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace bruce_i18n {",
        "",
        "struct CjkGlyph {",
        "    uint16_t codepoint;",
        "    uint16_t rows12[12]; // 12x12 bitmap (MSB = leftmost pixel in bits 11..0)",
        "#if !defined(BRUCE_COMPACT_CJK_FONT)",
        "    uint16_t rows16[16]; // 16x16 bitmap (MSB = leftmost pixel in bits 15..0)",
        "#endif",
        "};",
        "",
        "#if defined(BRUCE_COMPACT_CJK_FONT)",
        "#define BRUCE_CJK_R16(...)",
        "#else",
        "#define BRUCE_CJK_R16(...) , {__VA_ARGS__}",
        "#endif",
        "",
        f"static constexpr size_t kCjkGlyphCount = {len(codepoints)};",
        "",
        "static const CjkGlyph kCjkGlyphs[kCjkGlyphCount] PROGMEM = {",
    ]

    for cp in codepoints:
        ch = chr(cp)
        r12 = rasterize_glyph(ch, font12, 12)
        r16 = rasterize_glyph(ch, font16, 16)
        r12_str = ", ".join(f"0x{v:03X}" for v in r12)
        r16_str = ", ".join(f"0x{v:04X}" for v in r16)
        safe_comment = ch if ch not in ("\\", "*/") else ""
        lines.append(f"    {{0x{cp:04X}, {{{r12_str}}} BRUCE_CJK_R16({r16_str})}}, // {safe_comment}")

    lines += [
        "};",
        "#undef BRUCE_CJK_R16",
        "",
        "} // namespace bruce_i18n",
        "",
        "#endif // __BRUCE_CJK_FONT_DATA_H__",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Bruce Firmware CJK bitmap font header")
    parser.add_argument("--check", action="store_true", help="Verify table sort order and header freshness")
    args = parser.parse_args()

    entries = parse_and_validate_table(LANG_HEADER)
    codepoints = collect_codepoints(entries)
    font_path = find_cjk_font()
    header = generate_header(codepoints, font_path)

    if args.check:
        if not OUT_HEADER.is_file():
            print(f"ERROR: {OUT_HEADER} does not exist. Run without --check.", file=sys.stderr)
            return 1
        existing = OUT_HEADER.read_text(encoding="utf-8")
        if existing != header:
            print(f"ERROR: {OUT_HEADER} is out of date. Run tools/gen_cjk_font.py.", file=sys.stderr)
            return 1
        print(
            f"OK: {len(entries)} translations strictly sorted, "
            f"{len(codepoints)} unique CJK glyphs ({len(codepoints) * 58} bytes PROGMEM)."
        )
        return 0

    OUT_HEADER.write_text(header, encoding="utf-8")
    print(
        f"Generated {OUT_HEADER.relative_to(REPO_ROOT)}: "
        f"{len(entries)} translations, {len(codepoints)} glyphs "
        f"(~{len(codepoints) * 58} bytes PROGMEM)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
